#!/usr/bin/env python3
"""Generates protocol/test-vectors/packets.json.

An implementation of the framing that is independent of the Swift sender and the Kotlin receiver,
so both can be tested against the same bytes. Run after changing docs/PROTOCOL.md:

    python3 protocol/generate_test_vectors.py
"""
import json
import pathlib
import struct


def packet(type_, pts, payload):
    return struct.pack(">IBQ", len(payload), type_, pts) + payload


def hello(version, name):
    return struct.pack(">H", version) + name.encode("utf-8")


def volume(level, gain, muted):
    return struct.pack(">ffB", level, gain, 1 if muted else 0)


def config(width, height, sps, pps):
    return struct.pack(">HHH", width, height, len(sps)) + sps + struct.pack(">H", len(pps)) + pps


SPS = bytes.fromhex("6764002aac2b40780227e5c05a808080a0000003002000000781e30632")
PPS = bytes.fromhex("68ee3cb0")

vectors = [
    {"name": "ping", "type": 5, "ptsMicros": 0, "payload": b""},
    {"name": "bye", "type": 4, "ptsMicros": 0, "payload": b""},
    {"name": "hello", "type": 6, "ptsMicros": 0, "payload": hello(1, "Studio Mac — Beamly"),
     "expected": {"protocolVersion": 1, "deviceName": "Studio Mac — Beamly"}},
    {"name": "volume", "type": 7, "ptsMicros": 0, "payload": volume(0.5, 0.125, False),
     "input": {"volume": 0.5, "gain": 0.125, "muted": False},
     "expected": {"volume": 0.5, "gain": 0.125, "muted": False}},
    # The receiver must treat a muted sender as silent regardless of the gain field.
    {"name": "volume-muted", "type": 7, "ptsMicros": 0, "payload": volume(0.75, 0.25, True),
     "input": {"volume": 0.75, "gain": 0.25, "muted": True},
     "expected": {"volume": 0.75, "gain": 0.0, "muted": True}},
    {"name": "config", "type": 0, "ptsMicros": 0, "payload": config(1920, 1248, SPS, PPS),
     "expected": {"width": 1920, "height": 1248, "spsHex": SPS.hex(), "ppsHex": PPS.hex()}},
    {"name": "key-frame", "type": 1, "ptsMicros": 1_234_567_890,
     "payload": bytes.fromhex("00000001" "6588840021ff") + bytes.fromhex("00000001" "06050102")},
    {"name": "audio", "type": 3, "ptsMicros": 42, "payload": bytes(range(16))},
]

# AVCC (4-byte big-endian NAL lengths) -> Annex-B (start codes), as done by the macOS sender.
avcc_cases = [
    {"name": "two-nal-units", "avccHex": "00000003aabbcc" "00000002ddee", "annexBHex": "00000001aabbcc" "00000001ddee"},
    {"name": "truncated-length-stops", "avccHex": "00000002aabb" "000000ffcc", "annexBHex": "00000001aabb"},
    {"name": "empty", "avccHex": "", "annexBHex": ""},
]

out = {
    "comment": "Generated by protocol/generate_test_vectors.py. Do not edit by hand.",
    "protocolVersion": 1,
    "packets": [
        {**{k: v for k, v in vec.items() if k != "payload"},
         "payloadHex": vec["payload"].hex(),
         "encodedHex": packet(vec["type"], vec["ptsMicros"], vec["payload"]).hex()}
        for vec in vectors
    ],
    "avccToAnnexB": avcc_cases,
}
path = pathlib.Path(__file__).parent / "test-vectors" / "packets.json"
path.parent.mkdir(exist_ok=True)
path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
print(f"wrote {path}")
