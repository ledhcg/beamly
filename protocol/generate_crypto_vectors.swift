// Generates protocol/test-vectors/crypto.json for protocol version 2 (docs/PROTOCOL.md §4.2, §6, §7).
//
// Written directly from the specification with CryptoKit, independently of BeamlyKit, so the macOS sender
// and the Android receiver are both checked against the same reference bytes. Run from the repository root:
//
//     swift protocol/generate_crypto_vectors.swift
import CryptoKit
import Foundation

func hex(_ data: some DataProtocol) -> String { data.map { String(format: "%02x", $0) }.joined() }
func sha(_ label: String) -> Data { Data(SHA256.hash(data: Data(label.utf8))) }
func be<T: FixedWidthInteger>(_ value: T) -> Data { withUnsafeBytes(of: value.bigEndian) { Data($0) } }
func raw(_ secret: SharedSecret) -> Data { secret.withUnsafeBytes { Data($0) } }

// Deterministic keys: SHA-256 of a label as the private scalar (valid with overwhelming probability).
let macIdentity = try P256.KeyAgreement.PrivateKey(rawRepresentation: sha("beamly test: mac identity"))
let macEphemeral = try P256.KeyAgreement.PrivateKey(rawRepresentation: sha("beamly test: mac ephemeral"))
let tvIdentity = try P256.KeyAgreement.PrivateKey(rawRepresentation: sha("beamly test: tv identity"))
let tvEphemeral = try P256.KeyAgreement.PrivateKey(rawRepresentation: sha("beamly test: tv ephemeral"))
let deviceId = Data((0..<16).map { UInt8($0 * 17 & 0xff) })
let macName = "Studio Mac"
let tvName = "Living Room TV"

var hello = be(UInt16(2))
hello += deviceId + macIdentity.publicKey.x963Representation + macEphemeral.publicKey.x963Representation
hello += Data(macName.utf8)
var serverHello = Data([1])
serverHello += tvIdentity.publicKey.x963Representation + tvEphemeral.publicKey.x963Representation
serverHello += Data(tvName.utf8)

// §7 session keys, from the Mac's side.
var ikm = raw(try macEphemeral.sharedSecretFromKeyAgreement(with: tvEphemeral.publicKey))
ikm += raw(try macIdentity.sharedSecretFromKeyAgreement(with: tvEphemeral.publicKey))
ikm += raw(try macEphemeral.sharedSecretFromKeyAgreement(with: tvIdentity.publicKey))
let salt = Data(SHA256.hash(data: hello + serverHello))
let okm = HKDF<SHA256>.deriveKey(
    inputKeyMaterial: SymmetricKey(data: ikm), salt: salt, info: Data("beamly v2 session".utf8), outputByteCount: 64
).withUnsafeBytes { Data($0) }
let macToTv = okm.prefix(32)
let tvToMac = okm.suffix(32)

// §6 pairing.
let macNonce = sha("beamly test: mac nonce")
let tvNonce = sha("beamly test: tv nonce")
let commitment = Data(
    HMAC<SHA256>.authenticationCode(
        for: Data("beamly-pair-commit".utf8) + tvIdentity.publicKey.x963Representation
            + macIdentity.publicKey.x963Representation,
        using: SymmetricKey(data: tvNonce)))
let codeDigest = Array(
    SHA256.hash(
        data: Data("beamly-pair-code".utf8) + macIdentity.publicKey.x963Representation
            + tvIdentity.publicKey.x963Representation + macNonce + tvNonce))
let codeValue = (UInt32(codeDigest[0]) << 24 | UInt32(codeDigest[1]) << 16 | UInt32(codeDigest[2]) << 8
    | UInt32(codeDigest[3])) % 1_000_000

// §4.2 records.
func record(key: Data, counter: UInt64, type: UInt8, pts: UInt64, payload: Data) throws -> String {
    let nonce = try AES.GCM.Nonce(data: Data(count: 4) + be(counter))
    let box = try AES.GCM.seal(Data([type]) + be(pts) + payload, using: SymmetricKey(data: key), nonce: nonce)
    return hex(be(UInt32(box.ciphertext.count + 16)) + box.ciphertext + box.tag)
}
let audio = Data((0..<16).map { UInt8($0) })
let records: [[String: Any]] = [
    ["direction": "macToTv", "counter": 0, "type": 5, "ptsMicros": 0, "payloadHex": "",
     "recordHex": try record(key: macToTv, counter: 0, type: 5, pts: 0, payload: Data())],
    ["direction": "macToTv", "counter": 1, "type": 3, "ptsMicros": 42, "payloadHex": hex(audio),
     "recordHex": try record(key: macToTv, counter: 1, type: 3, pts: 42, payload: audio)],
    ["direction": "tvToMac", "counter": 0, "type": 14, "ptsMicros": 0, "payloadHex": "",
     "recordHex": try record(key: tvToMac, counter: 0, type: 14, pts: 0, payload: Data())],
]

let output: [String: Any] = [
    "comment": "Generated by protocol/generate_crypto_vectors.swift. Do not edit by hand.",
    "protocolVersion": 2,
    "keys": [
        "macIdentityPrivateHex": hex(macIdentity.rawRepresentation),
        "macIdentityPublicHex": hex(macIdentity.publicKey.x963Representation),
        "macEphemeralPrivateHex": hex(macEphemeral.rawRepresentation),
        "macEphemeralPublicHex": hex(macEphemeral.publicKey.x963Representation),
        "tvIdentityPrivateHex": hex(tvIdentity.rawRepresentation),
        "tvIdentityPublicHex": hex(tvIdentity.publicKey.x963Representation),
        "tvEphemeralPrivateHex": hex(tvEphemeral.rawRepresentation),
        "tvEphemeralPublicHex": hex(tvEphemeral.publicKey.x963Representation),
    ],
    "handshake": [
        "deviceIdHex": hex(deviceId), "macName": macName, "tvName": tvName,
        "helloPayloadHex": hex(hello), "serverHelloPayloadHex": hex(serverHello),
        "macToTvKeyHex": hex(macToTv), "tvToMacKeyHex": hex(tvToMac),
    ],
    "pairing": [
        "macNonceHex": hex(macNonce), "tvNonceHex": hex(tvNonce),
        "commitmentHex": hex(commitment), "code": String(format: "%06u", codeValue),
    ],
    "records": records,
]
let json = try JSONSerialization.data(withJSONObject: output, options: [.prettyPrinted, .sortedKeys])
let url = URL(fileURLWithPath: "protocol/test-vectors/crypto.json")
try (json + Data("\n".utf8)).write(to: url)
print("wrote \(url.path)")
